UPDATE education_card
SET title = '저혈당 처치 후 혈당이 180을 넘었어요',
    body  = '저혈당을 처치한 뒤 분석 구간 안에서 혈당이 180 mg/dL을 넘은 값이 읽힌 날이 있어요. 처치량 조절은 담당 의료진과 상담하세요.'
WHERE trigger = 'REBOUND';
